"""Tests for package.json / package-lock.json (v1,v2,v3) / yarn.lock parsing."""

import json
import os
import tempfile
import unittest

from sbomtool.analyzer import analyze, integrity_findings
from sbomtool.errors import InputError
from sbomtool.parsers.node import parse_lock
from tests.support import write, write_json, finding_codes


def _project(tmp, prod=None, dev=None):
    pkg = {"name": "app", "version": "1.0.0"}
    if prod:
        pkg["dependencies"] = prod
    if dev:
        pkg["devDependencies"] = dev
    write_json(os.path.join(tmp, "package.json"), pkg)


class PackageLockV3Tests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        _project(self.tmp, {"left-pad": "^1.3.0", "@scope/pkg": "~2.1.0"},
                 {"vitest": "^1.0.0"})
        write_json(os.path.join(self.tmp, "package-lock.json"), {
            "name": "app", "version": "1.0.0", "lockfileVersion": 3,
            "packages": {
                "": {"name": "app", "version": "1.0.0"},
                "node_modules/left-pad": {
                    "version": "1.3.0",
                    "integrity": "sha512-QU0=" ,
                    "license": "WTFPL",
                    "dependencies": {"ms": "2.1.3"},
                },
                "node_modules/ms": {"version": "2.1.3", "integrity": "sha512-bX0="},
                "node_modules/@scope/pkg": {"version": "2.1.4", "license": "MIT"},
                "node_modules/vitest": {"version": "1.2.0", "dev": True},
            },
        })

    def test_components_and_scopes(self):
        sbom = analyze(self.tmp, use_local=False)
        self.assertEqual(sbom.components["npm:left-pad"].scope, "required")
        self.assertEqual(sbom.components["npm:vitest"].scope, "optional")
        self.assertEqual(sbom.components["npm:@scope/pkg"].version, "2.1.4")

    def test_transitive_edge(self):
        sbom = analyze(self.tmp, use_local=False)
        self.assertIn("npm:ms", sbom.components["npm:left-pad"].dependencies)

    def test_constraint_satisfaction(self):
        sbom = analyze(self.tmp, use_local=False)
        codes = finding_codes(integrity_findings(sbom))
        self.assertNotIn("VERSION_MISMATCH", codes)  # ^1.3.0 ok, ~2.1.0 ok

    def test_bad_integrity_rejected(self):
        write_json(os.path.join(self.tmp, "package-lock.json"), {
            "lockfileVersion": 3,
            "packages": {"node_modules/x": {"version": "1.0.0",
                                            "integrity": "sha512-not*base64*"}},
        })
        with self.assertRaises(InputError):
            analyze(self.tmp, use_local=False)


class PackageLockV1Tests(unittest.TestCase):
    def test_nested_dependencies_tree(self):
        tmp = tempfile.mkdtemp()
        _project(tmp, {"a": "^1.0.0"})
        write_json(os.path.join(tmp, "package-lock.json"), {
            "name": "app", "version": "1.0.0", "lockfileVersion": 1,
            "dependencies": {
                "a": {
                    "version": "1.0.0",
                    "requires": {"b": "2.0.0"},
                    "dependencies": {
                        "b": {"version": "2.0.0", "shasum": "abcd1234",
                              "requires": {"c": "3.0.0"},
                              "dependencies": {
                                  "c": {"version": "3.0.0",
                                        "shasum": "abcd1234"}}},
                    },
                },
            },
        })
        sbom = analyze(tmp, use_local=False)
        self.assertEqual(set(sbom.components),
                         {"npm:a", "npm:b", "npm:c"})
        self.assertIn("npm:b", sbom.components["npm:a"].dependencies)
        c = sbom.components["npm:c"]
        self.assertTrue(any(h.alg == "sha1" for h in c.hashes))


class YarnV1Tests(unittest.TestCase):
    YARN = '''\
# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT.

"@scope/x@^2.0.0":
  version "2.0.3"
  resolved "https://example.invalid/x-2.0.3.tgz#deadbeef"
  integrity sha512-QU0=
  dependencies:
    ms "^2.1.1"

left-pad@^1.0.0, left-pad@~1.2:
  version "1.3.0"
  integrity sha1-bX0=

ms@^2.1.1:
  version "2.1.3"
  integrity sha512-ZZ0=
'''

    def test_yarn_parse(self):
        tmp = tempfile.mkdtemp()
        _project(tmp, {"left-pad": "^1.0.0", "@scope/x": "^2.0.0"})
        write(os.path.join(tmp, "yarn.lock"), self.YARN)
        sbom = analyze(tmp, use_local=False)
        self.assertEqual(sbom.components["npm:@scope/x"].version, "2.0.3")
        self.assertIn("npm:ms", sbom.components["npm:@scope/x"].dependencies)
        self.assertTrue(sbom.components["npm:ms"].hashes)

    def test_berry_lock_rejected(self):
        from sbomtool.models import Ecosystem
        tmp = tempfile.mkdtemp()
        write(os.path.join(tmp, "yarn.lock"),
              '__metadata:\n  version: 6\n\n"x@npm:^1.0.0":\n  version: 1.0.0\n')
        with self.assertRaises(InputError):
            parse_lock(os.path.join(tmp, "yarn.lock"), "yarn")

    def test_malformed_yarn_rejected(self):
        tmp = tempfile.mkdtemp()
        write(os.path.join(tmp, "yarn.lock"), "no-colon-header\n  version 1.0.0\n")
        with self.assertRaises(InputError):
            from sbomtool.models import Ecosystem
            parse_lock(os.path.join(tmp, "yarn.lock"), "yarn")


class CorruptInputsTests(unittest.TestCase):
    def test_malformed_package_json(self):
        tmp = tempfile.mkdtemp()
        write(os.path.join(tmp, "package.json"), "{ broken json")
        with self.assertRaises(InputError):
            analyze(tmp, use_local=False)

    def test_malformed_pyproject(self):
        tmp = tempfile.mkdtemp()
        write(os.path.join(tmp, "pyproject.toml"), "name = = =")
        with self.assertRaises(InputError):
            analyze(tmp, use_local=False)

    def test_malformed_uv_lock(self):
        tmp = tempfile.mkdtemp()
        write(os.path.join(tmp, "pyproject.toml"), '[project]\nname="d"\n')
        write(os.path.join(tmp, "uv.lock"), "version = 1\npackage = 123\n")
        with self.assertRaises(InputError):
            analyze(tmp, use_local=False)

    def test_unsupported_lockfile_version(self):
        tmp = tempfile.mkdtemp()
        _project(tmp)
        write_json(os.path.join(tmp, "package-lock.json"),
                   {"lockfileVersion": 99, "packages": {}})
        with self.assertRaises(InputError):
            analyze(tmp, use_local=False)


if __name__ == "__main__":
    unittest.main(verbosity=2)
